begin;
do $test$
declare boss uuid; worker uuid; ctx jsonb; owner_ctx jsonb; next_payload jsonb; rev bigint; saved bigint; original_payload jsonb; cnt integer; file_count integer; expected_files integer;
begin
 select owner into boss from billflow_private.workspace where id=1;
 select payload into original_payload from public.billflow_ledgers where owner=boss;
 select count(*) into expected_files from storage.objects where bucket_id='billflow-receipts' and (storage.foldername(name))[1]=boss::text;
 select user_id into worker from public.billflow_members where enabled and 'people'=any(edit_menus) and not('payroll'=any(menus)) limit 1;
 perform set_config('request.jwt.claim.sub',boss::text,true);
 set local role authenticated;
 owner_ctx:=public.billflow_access_context();
 reset role;
 perform set_config('request.jwt.claim.sub',worker::text,true);
 set local role authenticated;
 ctx:=public.billflow_access_context();
 if ctx->'access'->>'workspaceOwner'<>boss::text or ctx->'payload'->'entries' is distinct from owner_ctx->'payload'->'entries' or ctx->>'revision'<>owner_ctx->>'revision' then raise exception 'SHARED_READ_FAILED';end if;
 select count(*) into file_count from storage.objects where bucket_id='billflow-receipts';
 if file_count<>expected_files then raise exception 'SHARED_ATTACHMENTS_FAILED:%',file_count;end if;
 next_payload:=jsonb_set(ctx->'payload','{contacts}',(ctx->'payload'->'contacts')||'[{"id":"qa-shared-contact","code":"QA-SHARED","kind":"customer","name":"QA shared rollback","note":"","active":true}]');
 rev:=(ctx->>'revision')::bigint;
 saved:=public.billflow_save_workspace(next_payload,rev);
 begin perform public.billflow_save_workspace(next_payload,rev);raise exception 'STALE_WRITE_ACCEPTED';exception when others then if sqlerrm<>'CONFLICT' then raise;end if;end;
 begin perform public.billflow_save_workspace(jsonb_set(next_payload,'{business}','"forbidden"'),saved);raise exception 'FORBIDDEN_CHANGE_ACCEPTED';exception when others then if sqlerrm not like 'MENU_FORBIDDEN:%' then raise;end if;end;
 begin perform public.billflow_save_ledger(next_payload,rev);raise exception 'LEGACY_WRITE_ACCEPTED';exception when insufficient_privilege then null;end;
 begin update public.billflow_ledgers set payload=next_payload where owner=worker;raise exception 'DIRECT_WRITE_ACCEPTED';exception when insufficient_privilege then null;end;
 reset role;
 perform set_config('request.jwt.claim.sub',boss::text,true);
 set local role authenticated;
 owner_ctx:=public.billflow_access_context();
 if not exists(select 1 from jsonb_array_elements(owner_ctx->'payload'->'contacts') x where x->>'id'='qa-shared-contact') then raise exception 'OWNER_MISSED_MEMBER_SAVE';end if;
 if owner_ctx->'payload'->'entries' is distinct from original_payload->'entries' or owner_ctx->'payload'->'payroll' is distinct from original_payload->'payroll' then raise exception 'UNRELATED_DATA_CHANGED';end if;
 saved:=public.billflow_save_workspace(owner_ctx->'payload',(owner_ctx->>'revision')::bigint);
 reset role;
 update public.billflow_members set enabled=false where user_id=worker;
 perform set_config('request.jwt.claim.sub',worker::text,true);
 set local role authenticated;
 ctx:=public.billflow_access_context();
 if ctx->'payload'<>'null'::jsonb then raise exception 'REVOKED_READ';end if;
 select count(*) into cnt from storage.objects where bucket_id='billflow-receipts';
 if cnt<>0 then raise exception 'REVOKED_STORAGE';end if;
 begin perform public.billflow_save_workspace(next_payload,saved);raise exception 'REVOKED_WRITE';exception when others then if sqlerrm<>'READ_ONLY' then raise;end if;end;
 reset role;
end $test$;
rollback;
